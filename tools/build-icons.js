// Builds icons.js: only the game-icons.net glyphs the game actually references.
// Usage: npm install && npm run icons
// Icons by Lorc, Delapouite and contributors — https://game-icons.net (CC BY 3.0)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const { icons } = require('@iconify-json/game-icons/icons.json');
const sources = ['game-data.js', 'engine.js', 'ui.js', 'reference.js'].map(f => path.join(root, f)).filter(fs.existsSync);

const names = new Set();
sources.forEach(file => {
    const text = fs.readFileSync(file, 'utf8');
    for (const [, name] of text.matchAll(/['"`]([a-z0-9]+(?:-[a-z0-9]+)*)['"`]/g)) {
        if (icons[name]) names.add(name);
    }
});

const entries = [...names].sort().map(name => {
    const body = icons[name].body.replace(/fill="#fff"/g, 'fill="currentColor"');
    return `    ${JSON.stringify(name)}: ${JSON.stringify(body)}`;
});

const out = `// Generated by tools/build-icons.js — do not edit by hand.
// Icons by Lorc, Delapouite and contributors — https://game-icons.net (CC BY 3.0)
const ICONS = {
${entries.join(',\n')}
};
if (typeof module !== 'undefined') module.exports = ICONS;
`;
fs.writeFileSync(path.join(root, 'icons.js'), out);
console.log(`icons.js: ${names.size} icons, ${(out.length / 1024).toFixed(1)} KB`);
